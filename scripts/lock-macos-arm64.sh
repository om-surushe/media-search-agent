#!/usr/bin/env bash
# Regenerate the checked-in Apple Silicon dependency locks.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source "$ROOT/scripts/versions.env"
UV_BIN="${UV_BIN:-$HOME/.local/bin/uv}"
if [[ "$(uname -s)" != Darwin || "$(uname -m)" != arm64 ]]; then
  echo "Generate these locks on macOS Apple Silicon." >&2
  exit 1
fi
if [[ ! -x "$UV_BIN" ]]; then
  echo "uv not found at $UV_BIN; install the pinned version from scripts/versions.env." >&2
  exit 1
fi
UV_ACTUAL="$("$UV_BIN" --version | awk '{print $2}')"
if [[ "$UV_ACTUAL" != "$UV_VERSION" ]]; then
  echo "Expected uv $UV_VERSION, found $UV_ACTUAL at $UV_BIN." >&2
  exit 1
fi

make_input() {
  local output="$1" with_tests="$2"
  awk '/^[[:space:]]*(sentence-transformers|numpy|torch|facenet-pytorch)([[:space:]\[<>=!~]|$)/ {next} {print}' \
    "$ROOT/requirements-api.txt" > "$output"
  if [[ "$with_tests" == true ]]; then
    awk '/^[[:space:]]*(numpy|torch|facenet-pytorch)([[:space:]\[<>=!~]|$)/ {next} {print}' \
      "$ROOT/tests/requirements-ci.txt" >> "$output"
  fi
  cat >> "$output" <<'REQS'
numpy==1.26.4
torch==2.6.0
pydantic-settings==2.15.0
REQS
  if [[ "$with_tests" == true ]]; then
    # 1.12.0 supports the project's macOS 12 minimum; 1.15.x requires macOS 14.
    echo 'faiss-cpu==1.12.0' >> "$output"
  fi
}

API_INPUT="$(mktemp)"
DEV_INPUT="$(mktemp)"
trap 'rm -f "$API_INPUT" "$DEV_INPUT"' EXIT
make_input "$API_INPUT" false
make_input "$DEV_INPUT" true

"$UV_BIN" pip compile "$API_INPUT" --python-version 3.12 --python-platform aarch64-apple-darwin \
  --no-annotate --no-header -o "$ROOT/requirements-api-macos-arm64.lock"
"$UV_BIN" pip compile "$DEV_INPUT" --python-version 3.12 --python-platform aarch64-apple-darwin \
  --no-annotate --no-header -o "$ROOT/requirements-dev-macos-arm64.lock"
"$UV_BIN" pip compile "$ROOT/requirements-caption-macos-arm64.in" --python-version 3.12 \
  --no-annotate --no-header -o "$ROOT/requirements-caption-macos-arm64.lock"

for lock in requirements-api-macos-arm64.lock requirements-dev-macos-arm64.lock requirements-caption-macos-arm64.lock; do
  tmp="$ROOT/$lock.tmp"
  {
    echo '# Generated by scripts/lock-macos-arm64.sh; do not edit manually.'
    echo '# Target: CPython 3.12 / macOS arm64. Regenerate after requirements change.'
    cat "$ROOT/$lock"
  } > "$tmp"
  mv "$tmp" "$ROOT/$lock"
done
